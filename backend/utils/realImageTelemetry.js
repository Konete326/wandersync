export const resolveEntityImages = (type, query = '', country = '', city = '') => {
  const qLower = `${query} ${country} ${city}`.toLowerCase();

  for (const [key, pack] of Object.entries(REAL_IMAGE_LIBRARY)) {
    if (qLower.includes(key)) {
      return { coverImage: pack.cover, images: pack.gallery };
    }
  }

  const categoryPack = REAL_IMAGE_LIBRARY[type] || REAL_IMAGE_LIBRARY.spot;
  return { coverImage: categoryPack.cover, images: categoryPack.gallery };
};

export const resolveCityImage = (cityName = '', countryName = '') => {
  const q = `${cityName} ${countryName}`.toLowerCase();
  for (const [key, pack] of Object.entries(REAL_IMAGE_LIBRARY)) {
    if (q.includes(key)) {
      return pack.cover;
    }
  }
  return REAL_IMAGE_LIBRARY.spot.cover;
};
